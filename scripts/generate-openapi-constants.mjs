import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const openapiPath = path.join(rootDir, "openapi", "meilisearch-openapi.json");
const outputPath = path.join(
	rootDir,
	"src",
	"generated",
	"meilisearch-openapi-constants.ts",
);

const spec = JSON.parse(readFileSync(openapiPath, "utf8"));

const getEnum = (schemaName) => {
	const schema = spec.components?.schemas?.[schemaName];
	if (!Array.isArray(schema?.enum)) {
		throw new Error(`Missing enum schema: ${schemaName}`);
	}
	return schema.enum;
};

const actions = getEnum("Action");
const chatCompletionSources = getEnum("ChatCompletionSource");

const content = `// This file is generated by scripts/generate-openapi-constants.mjs.
// Do not edit it by hand.

export const MEILISEARCH_ACTIONS = ${JSON.stringify(actions, null, "\t")} as const;

export type MeilisearchAction = (typeof MEILISEARCH_ACTIONS)[number];

export const CHAT_COMPLETION_SOURCES = ${JSON.stringify(chatCompletionSources, null, "\t")} as const;

export type ChatCompletionSource = (typeof CHAT_COMPLETION_SOURCES)[number];
`;

writeFileSync(outputPath, content);

